const languageToggle = document.querySelector('.language-toggle');

function getSavedLanguage() {
  try {
    const savedLanguage = localStorage.getItem('turnbro-language');
    return ['th', 'en', 'zh'].includes(savedLanguage) ? savedLanguage : 'th';
  } catch {
    return 'th';
  }
}

function setLanguage(language) {
  const dictionary = translations[language];
  document.documentElement.lang = language === 'zh' ? 'zh-CN' : language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (translation) element.textContent = translation;
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const translation = dictionary[element.dataset.i18nHtml];
    if (translation) element.innerHTML = translation;
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const translation = dictionary[element.dataset.i18nAriaLabel];
    if (translation) element.setAttribute('aria-label', translation);
  });

  document.querySelectorAll('[data-i18n-content]').forEach((element) => {
    const translation = dictionary[element.dataset.i18nContent];
    if (translation) element.setAttribute('content', translation);
  });

  const translatedTitle = document.querySelector('[data-i18n-title]');
  if (translatedTitle) document.title = dictionary[translatedTitle.dataset.i18nTitle];

  if (languageToggle) {
    languageToggle.dataset.activeLanguage = language;
    languageToggle.querySelectorAll('[data-language]').forEach((option) => {
      const isActive = option.dataset.language === language;
      option.classList.toggle('active', isActive);
      option.setAttribute('aria-pressed', String(isActive));
    });
  }

  try {
    localStorage.setItem('turnbro-language', language);
  } catch {
    // The language switch still works when storage is unavailable.
  }
}

const initialLanguage = getSavedLanguage();
setLanguage(initialLanguage);

if (languageToggle) {
  languageToggle.addEventListener('click', (event) => {
    const selectedLanguage = event.target.closest('[data-language]');
    if (selectedLanguage) setLanguage(selectedLanguage.dataset.language);
  });
}

const menuButton = document.querySelector('.menu-button');
const navigation = document.querySelector('#site-nav');

if (menuButton && navigation) {
  menuButton.addEventListener('click', () => {
    const isOpen = navigation.classList.toggle('open');
    menuButton.setAttribute('aria-expanded', String(isOpen));
  });

  navigation.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => {
      navigation.classList.remove('open');
      menuButton.setAttribute('aria-expanded', 'false');
    });
  });
}

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 }
);

document.querySelectorAll('.reveal').forEach((element) => revealObserver.observe(element));

const projectCards = document.querySelectorAll('.project-card');
const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
const precisePointer = window.matchMedia('(hover: hover) and (pointer: fine)');

projectCards.forEach((card) => {
  card.addEventListener('pointermove', (event) => {
    if (reduceMotion.matches || !precisePointer.matches) return;

    const bounds = card.getBoundingClientRect();
    const x = (event.clientX - bounds.left) / bounds.width;
    const y = (event.clientY - bounds.top) / bounds.height;
    const rotateX = (0.5 - y) * 7;
    const rotateY = (x - 0.5) * 9;

    card.style.setProperty('--spot-x', `${x * 100}%`);
    card.style.setProperty('--spot-y', `${y * 100}%`);
    card.style.transform = `perspective(1000px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) translateY(-10px) scale(1.012)`;
  });

  card.addEventListener('pointerleave', () => {
    card.style.removeProperty('transform');
    card.style.setProperty('--spot-x', '50%');
    card.style.setProperty('--spot-y', '50%');
  });
});
